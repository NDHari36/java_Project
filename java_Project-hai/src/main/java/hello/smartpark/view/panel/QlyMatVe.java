    private void btnxacnhanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnxacnhanActionPerformed
        // TODO add your handling code here:
        if (currentTicket == null) return;

        int confirm = JOptionPane.showConfirmDialog(this,
                "Xác nhận xử lý mất vé cho xe " + currentTicket.getLicensePlate() +
                "\nTổng tiền thu: " + moneyFmt.format(currentTotalFee) + " đ?",
                "Xác nhận xử lý mất vé", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) return;

        try {
            dao.confirmLostTicket(currentTicket.getTicketId(), currentTotalFee);
            JOptionPane.showMessageDialog(this, "Đã xử lý mất vé và giải phóng vị trí đỗ thành công!");
            txtbienso.setText("");
            resetDisplay();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Lỗi xử lý mất vé:\n" + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnxacnhanActionPerformed


