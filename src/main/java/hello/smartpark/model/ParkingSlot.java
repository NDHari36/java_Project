package hello.smartpark.model;

/**
 *
 * @author PC
 */
public class ParkingSlot {

    private long slotId;
    private int parkingLotId;
    private String lotName;
    private String slotCode;
    private String areaName;
    private Integer allowedVehicleTypeId;
    private String slotStatus;
    private String availabilityStatus;

    public ParkingSlot() {
    }

    public long getSlotId() {
        return slotId;
    }

    public void setSlotId(long slotId) {
        this.slotId = slotId;
    }

    public int getParkingLotId() {
        return parkingLotId;
    }

    public void setParkingLotId(int parkingLotId) {
        this.parkingLotId = parkingLotId;
    }

    public String getLotName() {
        return lotName;
    }

    public void setLotName(String lotName) {
        this.lotName = lotName;
    }

    public String getSlotCode() {
        return slotCode;
    }

    public void setSlotCode(String slotCode) {
        this.slotCode = slotCode;
    }

    public String getAreaName() {
        return areaName;
    }

    public void setAreaName(String areaName) {
        this.areaName = areaName;
    }

    public Integer getAllowedVehicleTypeId() {
        return allowedVehicleTypeId;
    }

    public void setAllowedVehicleTypeId(Integer allowedVehicleTypeId) {
        this.allowedVehicleTypeId = allowedVehicleTypeId;
    }

    public String getSlotStatus() {
        return slotStatus;
    }

    public void setSlotStatus(String slotStatus) {
        this.slotStatus = slotStatus;
    }

    public String getAvailabilityStatus() {
        return availabilityStatus;
    }

    public void setAvailabilityStatus(String availabilityStatus) {
        this.availabilityStatus = availabilityStatus;
    }
}
