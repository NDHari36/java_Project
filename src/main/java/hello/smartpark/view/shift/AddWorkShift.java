    private void jButtonCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCreateActionPerformed
        // TODO add your handling code here:
        // 1. Lấy dữ liệu từ giao diện
        String tenCa = jTextFieldName.getText().trim();
        String start = jTextFieldStart.getText().trim();
        String end = jTextFieldEnd.getText().trim();
        String note = jTextFieldNote.getText().trim();

        int viTri = jComboBoxNhanVien.getSelectedIndex();

        if (viTri == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn nhân viên."
            );
            return;
        }

        User nhanVien = danhSachNhanVien.get(viTri);

        // 2. Kiểm tra dữ liệu
        if (tenCa.isEmpty() || start.isEmpty() || end.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng nhập đầy đủ thông tin ca làm việc."
            );
            return;
        }

        if (nhanVien == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn nhân viên."
            );
            return;
        }

        // 3. Chuyển đổi thời gian
        DateTimeFormatter formatter
                = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");

        LocalDateTime startAt;
        LocalDateTime endAt;

        try {
            startAt = LocalDateTime.parse(start, formatter);
            endAt = LocalDateTime.parse(end, formatter);

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Thời gian phải có định dạng yyyy-MM-dd HH:mm."
            );
            return;
        }

        if (!startAt.isBefore(endAt)) {
            JOptionPane.showMessageDialog(
                    this,
                    "Thời gian kết thúc phải sau thời gian bắt đầu."
            );
            return;
        }

        // 4. Tạo đối tượng WorkShift
        WorkShift ca = new WorkShift();

        ca.setShiftName(tenCa);
        ca.setStartAt(startAt);
        ca.setEndAt(endAt);
        ca.setNote(note);

        // 5. Tạo thông tin phân công nhân viên
        ShiftAssignment phanCong = new ShiftAssignment();

        phanCong.setUserId(nhanVien.getUserId());
        phanCong.setDuty("Nhân viên");

        List<ShiftAssignment> danhSachPhanCong = new ArrayList<>();
        danhSachPhanCong.add(phanCong);

        // 6. Gọi Controller tạo ca
        try {
            boolean ketQua = workShiftController.createShiftWithAssignments(
                    ca,
                    danhSachPhanCong
            );

            if (ketQua) {
                JOptionPane.showMessageDialog(
                        this,
                        "Tạo ca làm việc thành công!"
                );

                dispose();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "Tạo ca làm việc thất bại."
                );
            }

        } catch (SQLException | IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Lỗi tạo ca: " + e.getMessage()
            );
        }

    }//GEN-LAST:event_jButtonCreateActionPerformed

